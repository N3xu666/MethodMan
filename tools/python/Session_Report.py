#!/usr/bin/env python3
"""
Session_Report.py - Linux terminal session recorder for MethodMan.

Records a terminal session using script(1) from util-linux and produces a
walkthrough draft in the MethodMan section 3.2 format.

No keylogger. No /dev/input/event*. Only script(1) from util-linux.

Authorized use only. See ../../SECURITY.md.

By default the session runs in a clean `bash --noprofile --norc` subshell,
so the transcript is free of shell prompt redraw artifacts, syntax
highlighting, and multi-line prompts - regardless of the user's own shell
config (zsh, fish, oh-my-zsh, powerlevel10k, ...). Pass `--raw-shell` to
record inside your own $SHELL instead (transcript will contain redraw
artifacts; use --use-pyte to clean them).

Usage:
    python Session_Report.py start --machine <name> [--target <ip>]
                                   [--language en|ru|az] [--output <dir>]
                                   [--raw-shell] [--use-pyte]
    python Session_Report.py reclean <session_dir> [--use-pyte]

Exit codes:
    0 - session recorded / recleaned successfully
    1 - usage error or runtime failure
    2 - platform check failed (not Linux, or script(1) missing)
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import re
import shutil
import socket
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path


TOOL_VERSION = "0.3.0"
SUPPORTED_LANGUAGES = ("en", "ru", "az")
DEFAULT_OUTPUT_DIR = "sessions"
DEFAULT_CLEAN_SHELL = "/bin/bash"
DEFAULT_CLEAN_RC = "# Session_Report.py clean rc\nPS1='$ '\nunset PROMPT_COMMAND\nbind 'set enable-bracketed-paste off' 2>/dev/null || true\n"

# Optional dependency: pyte gives a correct terminal emulator for cleaning.
try:
    import pyte  # type: ignore
    HAS_PYTE = True
except ImportError:
    HAS_PYTE = False

# Runtime-built triple-backtick fence (keeps this source file free of
# literal triple-backtick sequences, which break Markdown rendering when
# the source is displayed inside a fenced block).
FENCE = chr(96) * 3

ANSI_ESCAPE_RE = re.compile(
    r"""
    \x1b
    (?:
        \[[0-?]*[ -/]*[@-~]
      | \][^\x07\x1b]*(?:\x07|\x1b\\)
      | [@-Z\\-_]
    )
    """,
    re.VERBOSE,
)

SCRIPT_BANNER_RE = re.compile(
    r"^Script (?:started on|done on|started, output file is|done, output file is) .*$",
    re.MULTILINE,
)


AI_PROMPT_TEMPLATE = """\
<!--
AI PROMPT - paste this draft into your AI assistant and ask it to complete
the walkthrough below in the MethodMan section 3.2 format.

Draft generated by Session_Report.py v{version} on {timestamp}.

Machine:  {machine}
Target:   {target}
Language: {language}
Shell:    {shell}

Instructions for the AI:
- Fill in every section placeholder marked with <TODO>.
- Follow the MethodMan section 3.2 walkthrough standard exactly:
  Attack Chain (tree), ethical NOTE, Machine Briefing, Reconnaissance,
  Foothold, Privilege Escalation, Flags, Key Takeaways.
- Add a CVE reference in the Exploitation section (NVD or MITRE link),
  or "No CVE (custom vulnerability)" with a one-sentence root cause.
- Show expected output after every key command (section 3.2.2).
- For OSCP machines, add "> [!IMPORTANT]" screenshot reminders
  (section 3.2.3).
- Use ASCII hyphen "-" only, never en/em dash (section 6.6).
- Mask all real flags, passwords, and hashes with the standard
  placeholders (section 6.2).
-->

# {machine} (HTB)

> Platform: Hack The Box
> OS: <TODO: Linux | Windows | FreeBSD | Solaris>
> Difficulty: <TODO: Easy | Medium | Hard | Insane>
> Result: <TODO: user | root | SYSTEM | Administrator>

---

## Attack Chain

{fence}text
<TODO: Recon -> Foothold -> Privesc (tree format)>
{fence}

> [!NOTE]
> All flags, passwords, hashes, and session tokens have been masked for ethical reasons.

---

## Machine Briefing

<TODO>

## Reconnaissance

<TODO>

## Foothold

<TODO>

## Exploitation

<TODO: CVE-YYYY-NNNNN (NVD: https://nvd.nist.gov/vuln/detail/CVE-YYYY-NNNNN)
or "No CVE (custom vulnerability or misconfiguration) - <root cause>">

## Privilege Escalation

<TODO>

## Flags

<TODO>

## Key Takeaways

<TODO>

---

## Raw Transcript

{fence}text
"""

FOOTER_TEMPLATE = """\
{fence}

*End of raw transcript. Draft generated by Session_Report.py v{version}.*
"""


def check_platform() -> None:
    if platform.system() != "Linux":
        sys.stderr.write(
            "ERROR: Session_Report.py is Linux-only.\n"
            "       It relies on script(1) from util-linux.\n"
            f"       Detected platform: {platform.system()}\n"
        )
        sys.exit(2)

    if shutil.which("script") is None:
        sys.stderr.write(
            "ERROR: script(1) not found in PATH.\n"
            "       Install util-linux (Debian/Ubuntu: apt install util-linux).\n"
        )
        sys.exit(2)


def _strip_ansi(raw: str) -> str:
    text = ANSI_ESCAPE_RE.sub("", raw)
    text = SCRIPT_BANNER_RE.sub("", text)
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    return text


def _clean_heuristic(raw: str) -> str:
    """
    stdlib-only cleaner. Sufficient for the default clean-shell mode
    (bash --noprofile --norc): bracketed paste, reverse-video echo, and
    cursor-forward sequences are all that remain, and they are ANSI-stripped.
    """
    text = _strip_ansi(raw)
    lines = text.split("\n")
    lines = ["" if ln.strip() == "" else ln for ln in lines]
    text = "\n".join(lines)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip() + "\n"


def _clean_with_pyte(raw: str) -> str:
    """
    Correct terminal-emulator cleanup via pyte.

    Needed only for --raw-shell mode, where the user's own shell (zsh,
    fish, powerlevel10k, oh-my-zsh, ...) emits cursor-move and redraw
    sequences that a regex cannot resolve.
    """
    if not HAS_PYTE:
        return _clean_heuristic(raw)

    screen = pyte.HistoryScreen(columns=200, lines=200, history=10000)
    stream = pyte.Stream(screen)

    text = SCRIPT_BANNER_RE.sub("", raw)
    stream.feed(text)

    result_lines: list[str] = []
    for line in screen.history.top:
        result_lines.append("".join(line[x].data for x in sorted(line.keys())))
    for y in range(screen.lines):
        row = screen.buffer[y]
        result_lines.append("".join(row[x].data for x in range(screen.columns)))

    cleaned = [ln.rstrip() for ln in result_lines]
    while cleaned and not cleaned[0].strip():
        cleaned.pop(0)
    while cleaned and not cleaned[-1].strip():
        cleaned.pop()
    text = "\n".join(cleaned)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip() + "\n"


def clean_transcript(raw: str, use_pyte: bool = False) -> str:
    """
    Clean a raw script(1) transcript.

    If use_pyte=True and pyte is installed, uses a real terminal emulator.
    Otherwise uses the stdlib-only heuristic cleaner.
    """
    if use_pyte:
        if not HAS_PYTE:
            sys.stderr.write(
                "WARN: --use-pyte requested but pyte is not installed. "
                "Falling back to heuristic cleaner.\n"
                "      Install pyte: pip install pyte\n"
            )
        return _clean_with_pyte(raw)
    return _clean_heuristic(raw)


def build_session_dir(output_root: Path, machine: str) -> Path:
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    safe_machine = re.sub(r"[^A-Za-z0-9_.-]+", "_", machine)
    session_dir = output_root / f"{safe_machine}-{timestamp}"
    session_dir.mkdir(parents=True, exist_ok=False)
    return session_dir


def _resolve_shell(args: argparse.Namespace) -> tuple[str, str, str]:
    """
    Return (shell_description, script_command, cleanup_hint).

    Default mode: clean bash without user rc, short PS1, no bracketed paste.
    --raw-shell: the user's own $SHELL, with user configs.
    """
    if args.raw_shell:
        user_shell = os.environ.get("SHELL") or "/bin/bash"
        return (
            f"{user_shell} (raw, user configs loaded)",
            user_shell,
            "raw-shell",
        )

    # Clean mode: bash --noprofile --norc, with a minimal temporary rc.
    bash = DEFAULT_CLEAN_SHELL
    if not Path(bash).exists():
        # Fallback: /bin/sh (POSIX, no bash-specific rc).
        return ("/bin/sh (clean fallback)", "/bin/sh", "clean")

    return (
        f"{bash} --noprofile --norc (clean, no user configs)",
        bash,
        "clean",
    )


def write_metadata(session_dir: Path, args: argparse.Namespace, shell_desc: str) -> None:
    try:
        operator = os.getlogin()
    except OSError:
        operator = os.environ.get("USER") or os.environ.get("LOGNAME") or "unknown"

    metadata = {
        "tool": "Session_Report.py",
        "tool_version": TOOL_VERSION,
        "machine": args.machine,
        "target": args.target or "",
        "started": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "host": socket.gethostname(),
        "operator": operator,
        "language": args.language,
        "shell": shell_desc,
        "raw_shell": bool(getattr(args, "raw_shell", False)),
    }
    path = session_dir / "metadata.json"
    path.write_text(json.dumps(metadata, indent=2, ensure_ascii=False) + "\n",
                    encoding="utf-8")


def write_draft_header(draft_path: Path, args: argparse.Namespace, shell_desc: str) -> None:
    content = AI_PROMPT_TEMPLATE.format(
        version=TOOL_VERSION,
        timestamp=datetime.now(timezone.utc).isoformat(timespec="seconds"),
        machine=args.machine,
        target=args.target or "<TODO: target IP>",
        language=args.language,
        shell=shell_desc,
        fence=FENCE,
    )
    draft_path.write_text(content, encoding="utf-8")


def append_transcript(draft_path: Path, cleaned: str) -> None:
    with draft_path.open("a", encoding="utf-8") as fh:
        fh.write(cleaned)
        fh.write(FOOTER_TEMPLATE.format(version=TOOL_VERSION, fence=FENCE))


def _build_script_cmd(raw_path: Path, args: argparse.Namespace,
                      shell_path: str, cleanup_hint: str) -> tuple[list[str], str | None]:
    """
    Return (argv, temp_rc_path_or_None).

    Clean mode uses bash --noprofile --norc --rcfile <temp> to enforce a
    minimal PS1 and disable bracketed paste.
    Raw mode uses the user's $SHELL with its own configs.
    """
    temp_rc: str | None = None

    if cleanup_hint == "clean" and shell_path.endswith("bash"):
        fd, temp_rc = tempfile.mkstemp(prefix="session-report-rc-", suffix=".sh")
        os.close(fd)
        Path(temp_rc).write_text(DEFAULT_CLEAN_RC, encoding="utf-8")
        inner = f"{shell_path} --noprofile --norc --rcfile {temp_rc}"
    else:
        inner = shell_path

    cmd = ["script", "-a", "-q", "-f", str(raw_path), "-c", inner]
    return cmd, temp_rc


def cmd_start(args: argparse.Namespace) -> int:
    check_platform()

    output_root = Path(args.output).expanduser().resolve()
    output_root.mkdir(parents=True, exist_ok=True)

    session_dir = build_session_dir(output_root, args.machine)
    raw_path = session_dir / "raw.txt"
    draft_path = session_dir / "walkthrough-draft.md"

    shell_desc, shell_path, cleanup_hint = _resolve_shell(args)
    write_metadata(session_dir, args, shell_desc)
    write_draft_header(draft_path, args, shell_desc)

    script_cmd, temp_rc = _build_script_cmd(raw_path, args, shell_path, cleanup_hint)

    print(f"[Session_Report] Session directory: {session_dir}")
    print(f"[Session_Report] Metadata:          {session_dir / 'metadata.json'}")
    print(f"[Session_Report] Draft:             {draft_path}")
    print(f"[Session_Report] Shell:             {shell_desc}")
    print(f"[Session_Report] Cleaner:           "
          f"{'pyte' if (args.use_pyte and HAS_PYTE) else 'heuristic'}")
    print(f"[Session_Report] Starting script(1). Type 'exit' to stop recording.")
    print()

    try:
        result = subprocess.run(script_cmd)
    except FileNotFoundError:
        sys.stderr.write("ERROR: failed to launch script(1).\n")
        return 1
    except KeyboardInterrupt:
        print("\n[Session_Report] Interrupted. Cleaning up.")
        result = None
    finally:
        if temp_rc and Path(temp_rc).exists():
            try:
                Path(temp_rc).unlink()
            except OSError:
                pass

    if not raw_path.exists():
        sys.stderr.write(
            "ERROR: raw.txt not found after script(1) exit.\n"
            "       Recording failed. Check that script(1) supports -f.\n"
        )
        return 1

    raw = raw_path.read_text(encoding="utf-8", errors="replace")
    cleaned = clean_transcript(raw, use_pyte=args.use_pyte)
    append_transcript(draft_path, cleaned)

    print()
    print(f"[Session_Report] Transcript cleaned: {len(raw)} -> {len(cleaned)} bytes.")
    print(f"[Session_Report] Final draft: {draft_path}")
    if result is not None and result.returncode != 0:
        print(f"[Session_Report] Note: script(1) exited with code {result.returncode}.")
    return 0


def cmd_reclean(args: argparse.Namespace) -> int:
    """
    Rebuild walkthrough-draft.md from an existing raw.txt, without
    re-recording. Useful after improving the cleaner or installing pyte.
    """
    session_dir = Path(args.session_dir).expanduser().resolve()
    if not session_dir.is_dir():
        sys.stderr.write(f"ERROR: session directory not found: {session_dir}\n")
        return 1

    raw_path = session_dir / "raw.txt"
    meta_path = session_dir / "metadata.json"
    draft_path = session_dir / "walkthrough-draft.md"

    if not raw_path.exists():
        sys.stderr.write(f"ERROR: raw.txt not found in {session_dir}\n")
        return 1
    if not meta_path.exists():
        sys.stderr.write(f"ERROR: metadata.json not found in {session_dir}\n")
        return 1

    meta = json.loads(meta_path.read_text(encoding="utf-8"))

    header_ns = argparse.Namespace(
        machine=meta.get("machine", "Unknown"),
        target=meta.get("target", "") or None,
        language=meta.get("language", "en"),
    )

    raw = raw_path.read_text(encoding="utf-8", errors="replace")
    cleaned = clean_transcript(raw, use_pyte=args.use_pyte)

    shell_desc = meta.get("shell", "unknown")
    write_draft_header(draft_path, header_ns, shell_desc)
    append_transcript(draft_path, cleaned)

    print(f"[Session_Report] Recleaned: {session_dir}")
    print(f"[Session_Report] Cleaner:   "
          f"{'pyte' if (args.use_pyte and HAS_PYTE) else 'heuristic'}")
    print(f"[Session_Report] Raw:       {len(raw)} bytes")
    print(f"[Session_Report] Cleaned:   {len(cleaned)} bytes")
    print(f"[Session_Report] Draft:     {draft_path}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="Session_Report.py",
        description="Record a Linux terminal session and produce a MethodMan "
                    "walkthrough draft (section 3.2 format).",
    )
    parser.add_argument("--version", action="version",
                        version=f"Session_Report.py {TOOL_VERSION}")
    sub = parser.add_subparsers(dest="command", required=True)

    start = sub.add_parser("start", help="Start a recording session.")
    start.add_argument("--machine", required=True,
                       help="Machine name (e.g. 'Layover').")
    start.add_argument("--target", default=None,
                       help="Target IP or hostname (optional).")
    start.add_argument("--language", choices=SUPPORTED_LANGUAGES, default="en",
                       help="Walkthrough language (default: en).")
    start.add_argument("--output", default=DEFAULT_OUTPUT_DIR,
                       help=f"Output root directory (default: {DEFAULT_OUTPUT_DIR}).")
    start.add_argument("--raw-shell", action="store_true",
                       help="Record in your own $SHELL with its configs "
                            "(may produce prompt redraw artifacts in the transcript).")
    start.add_argument("--use-pyte", action="store_true",
                       help="Use pyte terminal emulator for cleanup "
                            "(requires: pip install pyte). Recommended with --raw-shell.")
    start.set_defaults(func=cmd_start)

    reclean = sub.add_parser(
        "reclean",
        help="Rebuild walkthrough-draft.md from an existing session directory.",
    )
    reclean.add_argument("session_dir",
                         help="Path to an existing sessions/<machine>-<ts>/ directory.")
    reclean.add_argument("--use-pyte", action="store_true",
                         help="Use pyte terminal emulator for cleanup "
                              "(requires: pip install pyte).")
    reclean.set_defaults(func=cmd_reclean)

    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())